jest.mock('@react-native-async-storage/async-storage', () => require('@react-native-async-storage/async-storage/jest/async-storage-mock'));
jest.mock('@react-navigation/native', () => ({ useFocusEffect: callback => require('react').useEffect(callback, [callback]) }));
jest.mock('../../context/ProfileContext', () => ({ useProfile: () => ({ profile: { units: 'metric' } }) }));
jest.mock('../../storage/session', () => ({ getSession: () => ({ user: { id: 'alice' } }), accountKey: key => `alice:${key}` }));
jest.mock('../../api/client', () => ({ api: { get: jest.fn() } }));
jest.mock('../../storage/meals', () => ({ loadMealsFor: jest.fn(async () => [{ id: 'm', name: 'Oats', calories: 350 }]) }));
jest.mock('../../services/mealSync', () => ({ reconcileMealDays: jest.fn(async () => []) }));
jest.mock('../../services/progress', () => ({ ...jest.requireActual('../../services/progress'), cachedProgress: jest.fn(), fetchProgress: jest.fn() }));
const React = require('react');
const { act, create } = require('react-test-renderer');
const { Text } = require('react-native');
const { Action } = require('../../design/components');
const { cachedProgress, fetchProgress } = require('../../services/progress');
const { reconcileMealDays } = require('../../services/mealSync');
const Screen = require('../HistoryScreen').default;
let tree;
const fixture = dates => dates.map(date => ({ date, mealCount: 1, calories: 350, protein: 0, carbs: 20, fat: 10, fiber: null, steps: null, waterMl: null, weightKg: null, workouts: null }));
const button = label => tree.root.findAllByType(Action).find(n => n.props.label === label);
const output = () => tree.root.findAllByType(Text).map(n => n.props.children).flat(Infinity).join(' ');
beforeEach(() => { jest.clearAllMocks(); cachedProgress.mockImplementation(async dates => fixture(dates)); fetchProgress.mockImplementation(async dates => fixture(dates)); });
afterEach(async () => { if (tree) await act(async () => tree.unmount()); });
it('loads current and comparison windows for 7/30/90 days and pages older history', async () => {
  await act(async () => { tree = create(<Screen />); });
  expect(fetchProgress.mock.calls[0][0]).toHaveLength(14);
  expect(button('Newer 7 days').props.disabled).toBe(true);
  await act(async () => button('30 days').props.onPress());
  expect(fetchProgress.mock.calls.at(-1)[0]).toHaveLength(60);
  await act(async () => button('90 days').props.onPress());
  expect(fetchProgress.mock.calls.at(-1)[0]).toHaveLength(180);
  await act(async () => button('Older 90 days').props.onPress());
  expect(button('Newer 90 days').props.disabled).toBe(false);
});
it('keeps cached records visible on failure without best-day or deficit classifications', async () => {
  fetchProgress.mockRejectedValue(new Error('offline'));
  await act(async () => { tree = create(<Screen />); });
  expect(output()).toContain('Showing saved records');
  expect(output()).toContain('350');
  expect(output()).not.toContain('Best day');
  expect(output()).not.toContain('On target');
  expect(button('Retry progress')).toBeDefined();
});
it('ignores superseded responses and hydrates only the selected diary', async () => {
  let finish;
  fetchProgress.mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  await act(async () => { tree = create(<Screen />); });
  await act(async () => button('30 days').props.onPress());
  await act(async () => finish([{ ...fixture(['2000-01-01'])[0], calories: 99999 }]));
  expect(output()).not.toContain('99999');
  const day = tree.root.findAll(n => n.props.accessibilityRole === 'button' && /meal records$/.test(n.props.accessibilityLabel || ''))[0];
  await act(async () => day.props.onPress());
  expect(reconcileMealDays).toHaveBeenCalledTimes(1);
  expect(reconcileMealDays.mock.calls[0][0]).toHaveLength(1);
  expect(output()).toContain('Oats');
});
