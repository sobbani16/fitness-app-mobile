jest.mock('@react-native-async-storage/async-storage', () => require('@react-native-async-storage/async-storage/jest/async-storage-mock'));
jest.mock('../../components/KeyboardAwareScrollView', () => ({ children }) => children);
jest.mock('../../components/FeedbackAttachment', () => () => null);
const mockPrevent = jest.fn(), mockDispatch = jest.fn();
jest.mock('@react-navigation/native', () => ({ useNavigation: () => ({ dispatch: mockDispatch }), useRoute: () => ({ params: { source: 'Dashboard' } }), usePreventRemove: (...args) => mockPrevent(...args) }));
jest.mock('../../services/feedback', () => ({ composeFeedback: jest.fn(), feedbackScreen: () => 'Today', redactFeedback: text => text }));
const React = require('react'), { create, act } = require('react-test-renderer');
const { Alert } = require('react-native');
const { Action, Field } = require('../../design/components');
const { composeFeedback } = require('../../services/feedback');
const Screen = require('../FeedbackScreen').default;
let tree;
const button = label => tree.root.findAllByType(Action).find(n => n.props.label === label);
afterEach(async () => { if (tree) await act(async () => tree.unmount()); jest.restoreAllMocks(); });
it('requires review, blocks duplicate drafts and preserves cancelled content', async () => {
  const alert = jest.spyOn(Alert, 'alert').mockImplementation(() => {});
  composeFeedback.mockResolvedValue({ message: 'Cancelled', completed: false });
  await act(async () => { tree = create(<Screen />); });
  await act(async () => tree.root.findByType(Field).props.onChangeText('A useful issue'));
  expect(button('Open email draft').props.disabled).toBe(true);
  await act(async () => button('I reviewed the text and image for private information').props.onPress());
  const send = button('Open email draft').props.onPress;
  await act(async () => { send(); send(); });
  expect(composeFeedback).toHaveBeenCalledTimes(1);
  expect(tree.root.findByType(Field).props.value).toBe('A useful issue');
  expect(button('Open email draft').props.disabled).toBe(true);
  const callback = mockPrevent.mock.calls.at(-1)[1]; callback({ data: { action: {} } });
  expect(alert).toHaveBeenCalled(); expect(mockDispatch).not.toHaveBeenCalled();
});
